"""Validate JSON scores and generate a read-only C catalog for ESP-IDF/host."""
import argparse
from decimal import Decimal, InvalidOperation
import json
import math
from pathlib import Path
import re

TICKS=96
NAMES=('C','C#','D','D#','E','F','F#','G','G#','A','A#','B')

def number(value, field):
    if isinstance(value,bool) or not isinstance(value,(int,float,Decimal)):
        raise ValueError(f'{field}: expected a number')
    value=Decimal(str(value))
    if not value.is_finite() or value<=0:raise ValueError(f'{field}: must be positive and finite')
    return value

def midi_name(note):
    if not isinstance(note,str) or not re.fullmatch(r'[A-G]#?[0-9]',note):raise ValueError(f'invalid note {note!r}')
    name,octave=note[:-1],int(note[-1]);
    if name not in NAMES:raise ValueError(f'invalid note {note!r}')
    midi=(octave+1)*12+NAMES.index(name)
    if not 80<=440*2**((midi-69)/12)<=2000:raise ValueError(f'note {note} outside 80–2000 Hz')
    return midi

def load_scores(directory):
    result=[];ids=set()
    for path in sorted(Path(directory).glob('*.json')):
        try:
            d=json.loads(path.read_text(),parse_float=Decimal)
            if not isinstance(d,dict):raise ValueError('expected object')
            ident=d['id'];title=d['title']
            if not isinstance(ident,str) or not re.fullmatch(r'[a-z0-9_-]{1,24}',ident) or ident in ids:raise ValueError('invalid or duplicate id')
            if not isinstance(title,str) or not title.strip() or len(title)>80 or any(ord(c)<32 for c in title):raise ValueError('invalid title')
            bpm=number(d['bpm'],'bpm')
            if bpm!=int(bpm) or bpm>65535:raise ValueError('bpm must be a positive integer <=65535')
            ts=d['time_signature']
            if not isinstance(ts,list) or len(ts)!=2 or any(type(v)!=int for v in ts) or not 1<=ts[0]<=32 or ts[1] not in (1,2,4,8,16,32):raise ValueError('invalid time signature')
            per_beat=TICKS*4//ts[1]; per_bar=per_beat*ts[0];offset=0;notes=[]
            if not isinstance(d['notes'],list) or not d['notes'] or len(d['notes'])>65535:raise ValueError('notes must be a nonempty array of <=65535 notes')
            for i,n in enumerate(d['notes'],1):
                if not isinstance(n,dict):raise ValueError(f'note {i}: expected object')
                midi=midi_name(n['note']);ticks=number(n['beats'],f'note {i} beats')*TICKS
                rounded=int(ticks.to_integral_value())
                if rounded<1 or rounded>65535 or abs(ticks-rounded)>Decimal('0.0001'):raise ValueError(f'note {i}: duration must be a multiple of 1/96 quarter beat')
                if offset//per_bar>=65535:raise ValueError('score too long')
                notes.append((midi,rounded,offset//per_bar+1,offset%per_bar))
                offset+=rounded
            ids.add(ident);result.append((ident,title,int(bpm),ts,notes))
        except (KeyError,TypeError,ValueError,InvalidOperation,OverflowError) as exc:raise ValueError(f'{path.name}: {exc}') from exc
    if not result:raise ValueError('no JSON scores found')
    return result

def generate(directory,output):
    scores=load_scores(directory);lines=['/* Generated by compile_scores.py; do not edit. */','#include "practice_score.h"']
    for i,(_,_,_,_,notes) in enumerate(scores):
        lines.append(f'static const practice_score_note_t notes_{i}[] = {{')
        lines.extend(f'    {{{m}, {ticks}, {bar}, {beat}}},' for m,ticks,bar,beat in notes)
        lines.append('};')
    lines.append('const practice_score_t practice_scores[] = {')
    for i,(id,title,bpm,ts,notes) in enumerate(scores):
        lines.append(f'    {{{json.dumps(id)}, {json.dumps(title,ensure_ascii=False)}, {bpm}, {ts[0]}, {ts[1]}, notes_{i}, {len(notes)}}},')
    lines+=['};','const size_t practice_score_count = sizeof(practice_scores)/sizeof(practice_scores[0]);','']
    output=Path(output);output.parent.mkdir(parents=True,exist_ok=True);output.write_text('\n'.join(lines))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('directory',type=Path);p.add_argument('output',type=Path);a=p.parse_args()
    try:generate(a.directory,a.output)
    except (OSError,ValueError) as exc:p.error(str(exc))
